def _normalize(name: str) -> str:
    """공백을 없애고 대문자로 — ``Busan``·``BUSAN ``·``부산 항``이 같은 이름이 된다."""
    return "".join(name.split()).upper()


def authority_for_port(port_name: str | None) -> str | None:
    """항구 이름 → 항만청코드. 모르는 이름이면 ``None``(그 항차는 대조 불가)."""
    if not port_name:
        return None
    return _PORT_NAMES.get(_normalize(port_name))
