"""챗봇 용어 풀이 (`#123` Phase 3).

## 무엇을 만들고 무엇을 만들지 않았나

`#123` 본문은 **권고 엔진**(「속도를 1kn 줄이면 B등급으로 개선 가능합니다」)을 적었다.
2026-09-13 결정으로 **No-Advice를 유지**했으므로 권고는 만들지 않는다. 남은 것이
**설명 템플릿**이고, 그것이 이 모듈이다.

```
허용   "등급 C입니다. attained 4.98이 required 5.05보다 낮습니다."
허용   "화면에 계산해 두신 13kn 시나리오는 attained 4.61, 등급 B입니다."
금지   "속도를 1kn 줄이면 B등급으로 개선 가능합니다"      ← 행동 제안
금지   "13kn 시나리오가 더 낫습니다"                     ← 비교 표현
```

## ⚠️ 등급에 형용사를 붙이지 않는다

`#123` 본문의 예시는 「C(보통)」·「D(불량)」로 적혀 있다. **그 말은 정본 어디에도
없다.** 화면도 쓰지 않는다 — `GradeBadge`는 「등급 C」라고만 적는다.

여기서 「보통」을 만들면 **정본에 없는 제품 문구가 챗봇에서 처음 생긴다**
(``AGENTS §4.6`` 화면 문구 소관). 게다가 형용사는 **규제상 의미를 흐린다** —
`D`가 「불량」인 것이 아니라 **3년 연속이면 시정조치계획 의무가 생기는 등급**이다.
그 사실이 사용자가 실제로 알아야 하는 것이고, 정본에 있다(``PRD §3.3.7``).

그래서 이 풀이는 **정본 문장을 옮긴 것**이며, ``tests/test_chat_explain.py``가
원문과 대조한다.

## ⚠️ 두 자리 이상 숫자를 넣지 않는다

풀이에 규정 번호(`Reg 28.7`)나 임계값(`20%`)을 적으면, 모델이 그것을 답변에
인용하는 순간 :func:`~cii_platform.services.llm_guard.verify_numbers`가 **도구
응답에 없는 수치**로 보고 **답변을 통째로 폐기한다.**

가드를 느슨하게 푸는 대신 **풀이에서 숫자를 뺀다.** 규정 원문 인용은 챗봇의 일이
아니다 — 면책이 이미 *"최종 확인은 IMO 규제 원문을 따릅니다"*라고 말한다.
이 규칙은 검사가 강제한다.
"""

from __future__ import annotations

#: 등급의 뜻 — ``PRD §3.3.6``(판정)·``§3.3.7``(규제상 귀결).
#:
#: **형용사가 없다.** 위 머리말 참조.
GRADE_MEANING = (
    "CII 등급은 A부터 E까지이며, **CII 값이 낮을수록 더 우수한 등급**입니다. "
    "경계값과 정확히 같으면 더 우수한 등급으로 판정합니다. "
    "D등급이 여러 해 이어지거나 E등급을 받으면 시정조치계획을 세워 SEEMP에 반영할 "
    "의무가 생기며, 그 계획의 목표는 다음 해에 최소 C등급을 회복하는 것입니다."
)

#: ``attained`` vs ``required`` — ``PRD §3.3.1``·``§3.3.5``·``§3.3.6``.
#:
#: **이 도메인 밖에서는 직관에 어긋난다.** 「달성」이라는 말 때문에 클수록 좋다고
#: 읽기 쉬운데 반대다. 이것을 먼저 말하지 않으면 나머지 설명이 전부 거꾸로 읽힌다.
ATTAINED_VS_REQUIRED = (
    "attained CII는 실제 운항으로 나온 값이고, required CII는 그 해에 달성해야 하는 "
    "기준값입니다. **attained가 required보다 낮을수록 좋습니다** — 연료를 덜 태우고 "
    "같은 일을 했다는 뜻이기 때문입니다."
)

#: 위험도 4단계 — ``DESIGN_SYSTEM §2.5 (b)`` 🔒 라벨과 ``PRD §9.4.1`` 산정 근거.
#:
#: ⚠️ **화면과 같은 라벨을 쓴다.** 화면이 「높음 HIGH」로 적는데 챗봇이 「위험」이라고
#: 하면 같은 값을 두 이름으로 부르게 된다.
RISK_MEANING = (
    "위험도는 낮음 LOW · 보통 MEDIUM · 높음 HIGH · 심각 CRITICAL 네 단계입니다. "
    "현재 등급과, 한 단계 나쁜 등급 경계까지 남은 여유를 함께 보아 정해집니다. "
    "등급 E는 더 나빠질 등급이 없으므로 심각 CRITICAL입니다."
)

#: 다음 경계까지의 여유 — ``DESIGN_SYSTEM §2.5 (b)``.
#:
#: 필드 이름이 방향을 말해 주지 않는다. **악화 방향**이라는 것을 적지 않으면
#: 사용자가 「개선까지 남은 거리」로 읽는다.
BOUNDARY_GAP_MEANING = (
    "다음 경계까지의 여유는 **한 단계 나쁜 등급으로 떨어지기까지** 남은 폭입니다. "
    "개선 방향이 아니라 악화 방향입니다. 값이 작을수록 경계에 가깝습니다. "
    "등급 E는 더 나빠질 등급이 없어 이 값이 없습니다."
)

#: 모델에게 주는 풀이 묶음. 순서가 뜻을 만든다.
#:
#: :data:`ATTAINED_VS_REQUIRED`가 **먼저다** — 「낮을수록 좋다」를 모르면 나머지가
#: 전부 거꾸로 읽힌다.
GLOSSARY: tuple[tuple[str, str], ...] = (
    ("attained CII와 required CII", ATTAINED_VS_REQUIRED),
    ("등급", GRADE_MEANING),
    ("위험도", RISK_MEANING),
    ("다음 경계까지의 여유", BOUNDARY_GAP_MEANING),
)


def glossary_prompt() -> str:
    """풀이를 프롬프트 한 덩어리로 만든다.

    ## 도구가 아니라 프롬프트인 이유

    도구로 만들면 모델이 **용어를 물을 때마다 왕복이 한 번 더** 든다
    (``PRD §16.1`` 가드 2 — 왕복이 비용 폭주의 실제 경로다). 풀이는 정적이고
    짧으므로 매 호출에 실어 보내는 편이 싸다.

    ⚠️ **풀이는 수치를 주지 않는다.** 여기 있는 것은 뜻뿐이고, 값은 도구만 준다 —
    그래서 이 프롬프트가 커져도 No-Compute가 흔들리지 않는다.
    """
    header = (
        "다음은 이 도구가 쓰는 용어의 뜻입니다. 수치는 여기에 없습니다 — 도구가 준 값만 쓰십시오."
    )
    lines = [header]
    lines += [f"- **{term}**: {text}" for term, text in GLOSSARY]
    return "\n".join(lines)
