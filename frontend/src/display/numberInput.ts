/**
 * 숫자 입력 한 칸의 해석 (#2124).
 *
 * ## 화면이 적어 준 꼴을 화면이 받는다
 *
 * `DESIGN_SYSTEM §4.2` 「천단위 구분자」가 연료·거리·CO₂·용량을 `12,480`으로 보이게 한다.
 * 사용자는 그 값을 **보이는 대로** 입력 칸에 옮겨 적는다 — 실적 폼은 칸 바로 아래에
 * 「계획 12,480 nm」를 적어 두기까지 한다. 그런데 `Number('12,480')`은 `NaN`이라, 종전에는
 * 그 입력에 「0보다 커야 합니다」가 나갔다. **값이 틀린 것이 아니라 표기를 못 읽은 것**인데
 * 안내는 값을 탓했다.
 *
 * 그래서 두 가지를 정규화해 받는다.
 *
 * - **전각 숫자·기호** — 한글 입력기 상태에서 적힌 `１２４８０`·`．`·`，`·`－`. `NFKC`가
 *   반각으로 접는다.
 * - **천 단위 쉼표** — **세 자리씩 바르게 끊긴 것만.** `12,5`·`1,00`·`1,2345`는 받지 않는다.
 *   소수점을 쉼표로 적는 표기(`12,5` = 12.5)와 구분할 수 없는 꼴을 추측으로 읽으면
 *   **열 배 틀린 값이 조용히 저장된다.**
 *
 * ## 세 가지 답
 *
 * | 반환 | 뜻 |
 * |---|---|
 * | `null` | 비어 있다 — 「미입력」 |
 * | `NaN` | 적혀 있는데 **숫자로 읽을 수 없다** |
 * | 유한한 수 | 읽었다. 범위는 호출부가 본다 |
 *
 * 「읽을 수 없다」와 「범위를 벗어났다」는 사용자가 고칠 것이 다르므로 **호출부가 다른
 * 문구로 안내한다.** 둘을 한 갈래로 묶은 것이 `#2124`의 결함이었다.
 */

/** 세 자리씩 바르게 끊긴 천 단위 표기. 소수부에는 쉼표가 없다. */
const GROUPED = /^[+-]?\d{1,3}(,\d{3})+(\.\d*)?$/

export function readNumberInput(raw: string): number | null {
  const text = raw.normalize('NFKC').trim()
  if (text === '') return null
  const value = Number(GROUPED.test(text) ? text.replace(/,/g, '') : text)
  return Number.isFinite(value) ? value : Number.NaN
}
